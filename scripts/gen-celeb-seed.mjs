import fs from 'node:fs';
import path from 'node:path';

function readResults(jsonPath) {
  const raw = fs.readFileSync(jsonPath, 'utf8');
  const data = JSON.parse(raw);
  // Wrangler --json 형식: [{ results: [...], meta: {...} }]
  if (Array.isArray(data)) {
    if (data.length === 0) return [];
    const first = data[0];
    if (first && Array.isArray(first.results)) {
      return data.flatMap(entry => Array.isArray(entry.results) ? entry.results : []);
    }
    // 이미 레코드 배열인 경우 그대로 반환
    return data;
  }
  if (data && Array.isArray(data.results)) return data.results;
  if (data && data.result && Array.isArray(data.result)) return data.result;
  throw new Error(`Unrecognized JSON format in ${jsonPath}`);
}

function escapeSqlString(value) {
  return String(value).replaceAll("'", "''");
}

function sqlStr(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${escapeSqlString(value)}'`;
}

function sqlNum(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  if (Number.isNaN(Number(value))) return 'NULL';
  return String(Number(value));
}

function buildInsertCelebrities(celebs) {
  if (!celebs.length) return '';
  const columns = [
    'id',
    'birthYear',
    'birthMonth',
    'birthDay',
    'birthHour',
    'birthMinute',
    'calendar',
    'gender',
    'imageUrl'
  ];
  const values = celebs.map(c => `(${[
    sqlStr(c.id),
    sqlNum(c.birthYear),
    sqlNum(c.birthMonth),
    sqlNum(c.birthDay),
    sqlNum(c.birthHour),
    sqlNum(c.birthMinute),
    sqlStr(c.calendar),
    sqlStr(c.gender),
    sqlStr(c.imageUrl)
  ].join(', ')})`);
  return `INSERT INTO Celebrity (${columns.join(', ')})\nVALUES\n${values.join(',\n')};\n`;
}

function buildInsertTranslations(trans) {
  if (!trans.length) return '';
  const filtered = trans.filter(t => t.languageCode === 'ko');
  if (!filtered.length) return '';
  const columns = [
    'celebrityId',
    'languageCode',
    'name',
    'occupation',
    'description'
  ];
  const values = filtered.map(t => `(${[
    sqlStr(t.celebrityId),
    sqlStr(t.languageCode),
    sqlStr(t.name),
    sqlStr(t.occupation),
    sqlStr(t.description)
  ].join(', ')})`);
  return `INSERT INTO CelebrityTranslation (${columns.join(', ')})\nVALUES\n${values.join(',\n')};\n`;
}

function main() {
  const root = process.cwd();
  const tmpDir = path.join(root, 'tmp');
  const celebsPath = path.join(tmpDir, 'celebs.json');
  const transPath = path.join(tmpDir, 'translations.json');
  const outPath = path.join(tmpDir, 'seed_celeb.sql');

  if (!fs.existsSync(tmpDir)) fs.mkdirSync(tmpDir, { recursive: true });
  if (!fs.existsSync(celebsPath)) {
    throw new Error(`Missing file: ${celebsPath}. Export JSON first.`);
  }
  if (!fs.existsSync(transPath)) {
    throw new Error(`Missing file: ${transPath}. Export JSON first.`);
  }

  const celebs = readResults(celebsPath);
  const trans = readResults(transPath);

  const sqlParts = [];
  sqlParts.push('-- Generated by scripts/gen-celeb-seed.mjs');
  sqlParts.push('PRAGMA foreign_keys = OFF;');
  sqlParts.push('BEGIN TRANSACTION;');
  // Clear existing data in FK-safe order
  sqlParts.push('DELETE FROM CelebrityTranslation;');
  sqlParts.push('DELETE FROM Celebrity;');
  // Insert minimal columns only; other columns use defaults
  const celebsInsert = buildInsertCelebrities(celebs);
  if (celebsInsert) sqlParts.push(celebsInsert);
  const transInsert = buildInsertTranslations(trans);
  if (transInsert) sqlParts.push(transInsert);
  sqlParts.push('COMMIT;');
  sqlParts.push('PRAGMA foreign_keys = ON;');

  fs.writeFileSync(outPath, sqlParts.join('\n') + '\n', 'utf8');
  console.log(`Wrote SQL to: ${outPath}`);
}

main();


